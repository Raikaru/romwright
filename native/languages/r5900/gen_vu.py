#!/usr/bin/env python3
"""Generates vulanes.sinc and vuupper.sinc for the R5900 COP2 (VU0 macro mode) language.

The VU0 macro instructions are lane-wise on four f32 lanes with a dest mask, a broadcast
field and a handful of scalar registers. Hand-writing 80 constructors that differ only in
the operator invites copy-paste faults, so the constructors are generated from one table.
The generated files are committed; `gen_vu.py --check` verifies they match this script.

Representation (documented in docs/console-research.md, "VU0 macro mode"):
  * VF registers are four 4-byte lanes, x at the lowest address (lqc2/sqc2/qmfc2/qmtc2 move
    memory/GPR word k to lane k). Lane varnodes are named vfNx, vfNy, vfNz, vfNw.
  * ACC is vuACCx..w, I is vuI, Q is vuQ; VI registers are the 4-byte vi0..vi15 holding a
    16-bit value zero-extended.
  * A dest mask is resolved at decode time by lane tables (D*, E*, A*): a lane the mask
    clears (or vf0) is exported as a dead unique, a live lane as the register itself, so
    the decompiler sees straight-line per-lane code with no mask arithmetic.
"""
import sys, pathlib

LANES = "xyzw"
ONE = {"x": "0", "y": "0", "z": "0", "w": "0x3f800000"}   # vf0 = (0, 0, 0, 1.0)
ACC = {l: f"vuACC{l}" for l in LANES}

def lane_tables():
    o = []
    w = o.append
    w("# Lane tables for the VU0 macro instructions (generated by gen_vu.py; do not edit).")
    w("#")
    w("# Each table exports one lane as a 4-byte varnode. A destination table exports the")
    w("# register lane when the dest mask keeps it and the register is not vf0, otherwise a")
    w("# dead unique, so every constructor writes all four lanes and the decompiler deletes the")
    w("# masked ones. A source table exports vf0 as the constant (0, 0, 0, 1.0).")
    w("# Source: S (fs), T (ft). Destination: D (fd, masked), E (ft, masked), W (ft, unmasked),")
    w("# V (fs, unmasked), A (ACC, masked).")
    w("")
    w("define pcodeop _cfc2;")
    w("")
    for l in LANES:
        w(f"S{l}: vfs_{l}  is vufs != 0 & vfs_{l} {{ export vfs_{l}; }}")
        w(f"S{l}:         is vufs = 0 {{ export {ONE[l]}:4; }}")
    for l in LANES:
        w(f"T{l}: vft_{l}  is vuft != 0 & vft_{l} {{ export vft_{l}; }}")
        w(f"T{l}:         is vuft = 0 {{ export {ONE[l]}:4; }}")
    sink = "{ local t:4; export t; }"
    for l in LANES:
        w(f"D{l}: vfd_{l}  is vm{l} = 1 & vufd != 0 & vfd_{l} {{ export vfd_{l}; }}")
        w(f"D{l}:         is vm{l} = 1 & vufd = 0 {sink}")
        w(f"D{l}:         is vm{l} = 0 {sink}")
    for l in LANES:
        w(f"E{l}: vft_{l}  is vm{l} = 1 & vuft != 0 & vft_{l} {{ export vft_{l}; }}")
        w(f"E{l}:         is vm{l} = 1 & vuft = 0 {sink}")
        w(f"E{l}:         is vm{l} = 0 {sink}")
    for l in LANES:
        w(f"W{l}: vft_{l}  is vuft != 0 & vft_{l} {{ export vft_{l}; }}")
        w(f"W{l}:         is vuft = 0 {sink}")
    for l in LANES:
        w(f"V{l}: vfs_{l}  is vufs != 0 & vfs_{l} {{ export vfs_{l}; }}")
        w(f"V{l}:         is vufs = 0 {sink}")
    for l in LANES:
        w(f"A{l}:         is vm{l} = 1 {{ export vuACC{l}; }}")
        w(f"A{l}:         is vm{l} = 0 {sink}")
    w("")
    w("# Broadcast ft lane (bc field, bits 0-1), and the fsf / ftf selected scalar lanes.")
    for sel, field, reg, name in (("vubc", "vuft", "vft", "Bv"), ("vufsf", "vufs", "vfs", "Fsv"), ("vuftf", "vuft", "vft", "Ftv")):
        for i, l in enumerate(LANES):
            w(f"{name}: {reg}_{l}  is {sel} = {i} & {field} != 0 & {reg}_{l} {{ export {reg}_{l}; }}")
            w(f"{name}:         is {sel} = {i} & {field} = 0 {{ export {ONE[l]}:4; }}")
    w("")
    w("# Integer registers: vi0 reads as 0 and ignores writes. Values are 16 bits in a 4-byte")
    w("# register, every write masks to 16 bits.")
    for name, f, z in (("IRs", "vuis", "vzs"), ("IRt", "vuit", "vzt")):
        w(f"{name}: {f}  is {z} != 0 & {f} {{ export {f}; }}")
        w(f"{name}:      is {z} = 0 {{ export 0:4; }}")
    for name, f, z in (("IWd", "vuid", "vzd"), ("IWt", "vuit", "vzt"), ("IWs", "vuis", "vzs")):
        w(f"{name}: {f}  is {z} != 0 & {f} {{ export {f}; }}")
        w(f"{name}:      is {z} = 0 {sink}")
    w("")
    w("# COP2 control registers as the CFC2/CTC2 `fs` field names them: 0-15 VI, then Status,")
    w("# MAC, CLIP, -, R, I, Q, -, -, -, TPC, CMSAR0, FBRST, VPU-STAT, -, CMSAR1. A read is exact")
    w("# for the registers this language models (VI, CLIP, I, Q); Status, MAC, R and the")
    w("# VPU-controlled registers are changed by instructions or by the hardware without a")
    w("# model here, so reading them stays an opaque _cfc2 and the decompiler cannot fold a")
    w("# stale value into a branch. CcM is the width a write keeps (VI 16 bits, CLIP 24 bits).")
    w("CcR:       is vzs = 0 { export 0:4; }")
    w("CcR: vucc  is vzs >= 1 & vzs <= 15 & vucc { export vucc; }")
    for n in (18, 21, 22):
        w(f"CcR: vucc  is vzs = {n} & vucc {{ export vucc; }}")
    w("CcR:       is vzs >= 16 & vzs != 18 & vzs != 21 & vzs != 22 & vzi { local t:4 = _cfc2(vzi:1); export t; }")
    w("CcW: vucc  is vzs != 0 & vucc { export vucc; }")
    w(f"CcW:       is vzs = 0 {sink}")
    w("CcM:       is vucc < 16 { export 0xffff:4; }")
    w("CcM:       is vucc = 18 { export 0xffffff:4; }")
    w("CcM:       is vucc > 15 & vucc != 18 { export 0xffffffff:4; }")
    w("")
    return "\n".join(o) + "\n"

def tabs(*names):
    out = []
    for n in names:
        if n in ("S", "T", "D", "E", "W", "V", "A"):
            out += [f"{n}{l}" for l in LANES]
        else:
            out.append(n)
    return " & ".join(out)

