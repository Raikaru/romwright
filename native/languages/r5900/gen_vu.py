HDR = {h.split(" ")[0][1:]: h for h in HEADERS}

def hdr(key, *tables):
    h = HDR[key]
    return h + (" & " + tabs(*tables) if tables else "")

def body(lines, indent="    "):
    return "{\n" + "".join(f"{indent}{l}\n" for l in lines) + "}\n"

def lanewise(dst, expr, lanes=LANES):
    return [f"{dst}{l} = {expr(l)};" for l in lanes]

OPS = {  # operator on (acc, s, r) per lane
    "add": lambda l, r: f"S{l} f+ {r(l)}",
    "sub": lambda l, r: f"S{l} f- {r(l)}",
    "mul": lambda l, r: f"S{l} f* {r(l)}",
    "madd": lambda l, r: f"{ACC[l]} f+ (S{l} f* {r(l)})",
    "msub": lambda l, r: f"{ACC[l]} f- (S{l} f* {r(l)})",
}

def arith(out):
    """ADD/SUB/MUL/MADD/MSUB in register, I, Q and broadcast forms, into fd or into ACC."""
    for op in ("add", "sub", "mul", "madd", "msub"):
        # D forms
        forms = [
            (f"v{op}^dest", lambda l: f"T{l}", ("S", "T", "D"), []),
            (f"v{op}i^dest", lambda l: "vuI", ("S", "D"), []),
            (f"v{op}q^dest", lambda l: "vuQ", ("S", "D"), []),
            (f"v{op}^bc^dest", lambda l: "bcv", ("S", "Bv", "D"), ["local bcv:4 = Bv;"]),
        ]
        for key, r, t, pre in forms:
            out.append(hdr(key, *t))
            out.append(body(pre + lanewise("D", lambda l: OPS[op](l, r))))
        # ACC forms
        for key, r, t, pre in (
            (f"v{op}a^dest", lambda l: f"T{l}", ("S", "T", "A"), []),
            (f"v{op}ai^dest", lambda l: "vuI", ("S", "A"), []),
            (f"v{op}aq^dest", lambda l: "vuQ", ("S", "A"), []),
            (f"v{op}a^bc^dest", lambda l: "bcv", ("S", "Bv", "A"), ["local bcv:4 = Bv;"]),
        ):
            out.append(hdr(key, *t))
            out.append(body(pre + lanewise("A", lambda l: OPS[op](l, r))))

def maxmin(out):
    for op, keys in (("max", ("vmax^dest", "vmaxi^dest", "vmax^bc^dest")),
                     ("mini", ("vmini^dest", "vminii^dest", "vminibc^bc^dest"))):
        for key, r, t, pre in (
            (keys[0], lambda l: f"T{l}", ("S", "T", "D"), []),
            (keys[1], lambda l: "vuI", ("S", "D"), []),
            (keys[2], lambda l: "bcv", ("S", "Bv", "D"), ["local bcv:4 = Bv;"]),
        ):
            lines = list(pre)
            for l in LANES:
                cmp = f"S{l} f< {r(l)}" if op == "max" else f"{r(l)} f< S{l}"
                lines += [f"local m{l}:4 = S{l};",
                          f"if (!({cmp})) goto <keep{l}>;",
                          f"m{l} = {r(l)};",
                          f"<keep{l}>",
                          f"D{l} = m{l};"]
            out.append(hdr(key, *t))
            out.append(body(lines))

def conv(out):
    for n, scale in (("0", None), ("4", 0x41800000), ("12", 0x45800000), ("15", 0x47000000)):
        e = (lambda l, s=scale: f"trunc(S{l})" if s is None else f"trunc(S{l} f* {s:#x}:4)")
        out.append(hdr(f"vftoi{n}^dest", "S", "E"))
        out.append(body(lanewise("E", e)))
    for n, scale in (("0", None), ("4", 0x3d800000), ("12", 0x39800000), ("15", 0x38000000)):
        e = (lambda l, s=scale: f"int2float(S{l})" if s is None else f"int2float(S{l}) f* {s:#x}:4")
        out.append(hdr(f"vitof{n}^dest", "S", "E"))
        out.append(body(lanewise("E", e)))

