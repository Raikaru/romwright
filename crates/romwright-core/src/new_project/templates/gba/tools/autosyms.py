#!/usr/bin/env python3
"""Define the data the C units name by address: autosyms.py OUT OBJECT [OBJECT...]

The decompiler names a global it has no symbol for after its address (`DAT_03001234`,
`LAB_08758720`, `iRam0203a8f0`): the 8 hex digits are the address. A C unit that
references one leaves an undefined symbol; this script lists the undefined symbols of
the C objects (`nm -u`) whose name ends in 8 hex digits inside the GBA address map and
writes `name = 0xADDRESS;` for the linker. Names without an address in them stay
undefined, and the link stops on them.
"""
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
NAMED = re.compile(r"^[A-Za-z_]*?_?([0-9a-fA-F]{8})$")


def main():
    out, *objects = sys.argv[1:]
    nm = json.loads((ROOT / "build" / "tools.json").read_text())["nm"]
    # Functions are defined by their own objects (with the Thumb bit): never by address here.
    functions = {l.split(" = ")[0] for l in (ROOT / "config" / "symbols.txt").read_text().splitlines() if "type:func" in l}
    wanted = {}
    for obj in objects:
        result = subprocess.run([nm, "-u", obj], capture_output=True, text=True)
        for line in result.stdout.splitlines():
            name = line.split()[-1] if line.split() else ""
            match = NAMED.match(name)
            if match and name not in functions:
                address = int(match.group(1), 16)
                if 0x02000000 <= address < 0x0E000000:
                    wanted[name] = address
    text = "/* Generated by tools/autosyms.py: globals named by address in the C units. */\n"
    text += "".join(f'"{name}" = {address:#010x};\n' for name, address in sorted(wanted.items()))
    Path(out).parent.mkdir(parents=True, exist_ok=True)
    Path(out).write_text(text)


main()
